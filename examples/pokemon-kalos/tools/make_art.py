#!/usr/bin/env python3
"""
make_art.py - generates ../include/art.h (all sprites, tiles, font, map) from the
Python art sources in this folder.

usage: python3 make_art.py [--preview DIR]
  --preview DIR   also write creatures.png / world.png / tiles.png contact sheets
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from PIL import Image  # noqa: E402
import creatures  # noqa: E402
import world  # noqa: E402
import font  # noqa: E402
from artlib import to_image  # noqa: E402

OUT = os.path.join(HERE, "..", "include", "art.h")


def rgb565(c):
    r, g, b = c
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)


class Emitter:
    def __init__(self):
        self.lines = []
        self.bytes = 0

    def sprite(self, name, pix):
        h = len(pix)
        w = len(pix[0])
        pal = []
        idx = {}
        data = []
        for row in pix:
            for c in row:
                if c is None:
                    data.append(0)
                    continue
                k = rgb565(c)
                if k not in idx:
                    pal.append(k)
                    idx[k] = len(pal)
                data.append(idx[k])
        assert len(pal) < 256, name
        L = self.lines
        L.append("static const uint16_t PAL_%s[] = {0x0000,%s};" % (name, ",".join("0x%04X" % p for p in pal)))
        L.append("static const uint8_t PX_%s[] = {" % name)
        for i in range(0, len(data), 48):
            L.append("  " + ",".join(str(v) for v in data[i:i + 48]) + ",")
        L.append("};")
        L.append("static const Sprite SPR_%s = {%d, %d, PX_%s, PAL_%s};" % (name, w, h, name, name))
        L.append("")
        self.bytes += len(data) + 2 * len(pal)


def main():
    preview = None
    if "--preview" in sys.argv:
        preview = sys.argv[sys.argv.index("--preview") + 1]

    e = Emitter()
    L = e.lines
    L += [
        "// =============================================================================",
        "//  art.h - GENERATED by tools/make_art.py - do not edit by hand.",
        "//  Fan-tribute pixel art (Kalos creatures, trainer, Route tiles, font, map).",
        "// =============================================================================",
        "#pragma once",
        "#include <stdint.h>",
        "",
        "struct Sprite { uint16_t w, h; const uint8_t* px; const uint16_t* pal; };",
        "struct Glyph  { uint8_t w; uint8_t rows[8]; };",
        "struct MapObj { uint8_t kind; int16_t x, y; };",
        "",
    ]

    # creatures
    cre = {n: f() for n, f in creatures.ALL.items()}
    for n, pix in cre.items():
        e.sprite(n.upper(), pix)

    # tiles
    tiles = world.build_tiles()
    for n in world.TILE_ORDER:
        e.sprite("T_" + n.upper(), tiles[n])
    L.append("static const Sprite* const TILESET[] = {%s};" % ",".join("&SPR_T_" + n.upper() for n in world.TILE_ORDER))
    for i, n in enumerate(world.TILE_ORDER):
        L.append("#define TILE_%s %d" % (n.upper(), i))
    L.append("")

    # trainer
    tf = world.trainer_frames()
    for i, f in enumerate(tf):
        e.sprite("TRAINER%d" % i, f)
    L.append("static const Sprite* const TRAINER[12] = {%s};" % ",".join("&SPR_TRAINER%d" % i for i in range(12)))
    L.append("")

    # objects & fx
    objs = {"TREE": world.tree(), "LAMP": world.lamp(), "SIGN": world.sign(), "CENTER": world.pokecenter(),
            "BALL": world.pokeball(), "STAR": world.star(), "TALLOVER": world.tall_grass_overlay()}
    for n, p in objs.items():
        e.sprite(n, p)

    # font
    glyphs = {code: (w, bits) for code, w, bits in font.glyph_table()}
    L.append("static const Glyph FONT[128] = {")
    for code in range(128):
        w, bits = glyphs.get(code, (0, [0] * 8))
        L.append("  {%d,{%s}}, // %r" % (w, ",".join(str(b) for b in bits), chr(code)))
    L.append("};")
    L.append("")

    # map
    m = world.build_map()
    L.append("#define MAP_W %d" % world.MAP_W)
    L.append("#define MAP_H %d" % world.MAP_H)
    L.append("// . , grass | T tall grass | = path | r y o flowers | w water | h hedge | F fence")
    L.append("static const char MAP[MAP_H][MAP_W + 1] = {")
    for row in m:
        L.append('  "%s",' % row)
    L.append("};")
    kinds = {"tree": 0, "lamp": 1, "sign": 2, "center": 3}
    L.append("enum { OBJ_TREE, OBJ_LAMP, OBJ_SIGN, OBJ_CENTER };")
    L.append("static const MapObj MAP_OBJS[] = {")
    for k, x, y in world.OBJECTS:
        L.append("  {%d, %d, %d}," % (kinds[k], x, y))
    L.append("};")
    L.append("#define MAP_OBJ_COUNT %d" % len(world.OBJECTS))
    L.append("static const uint8_t ROUTE[][2] = {%s};" % ",".join("{%d,%d}" % p for p in world.ROUTE))
    L.append("#define ROUTE_LEN %d" % len(world.ROUTE))
    L.append("")

    with open(OUT, "w") as f:
        f.write("\n".join(L) + "\n")
    print("wrote %s (%d KB of art data)" % (os.path.relpath(OUT), e.bytes // 1024))

    if preview:
        os.makedirs(preview, exist_ok=True)
        render_world(m, tiles, objs, tf).resize((world.MAP_W * 16 * 2, world.MAP_H * 16 * 2), Image.NEAREST) \
            .save(os.path.join(preview, "world.png"))
        print("wrote world preview")


def render_world(m, tiles, objs, tf):
    W, H = world.MAP_W * 16, world.MAP_H * 16
    im = Image.new("RGBA", (W, H))
    ch2tile = {".": "grass", ",": "grass2", "T": "tall0", "=": "path", "r": "flowerR0", "y": "flowerY0",
               "o": "flowerW0", "w": "water0", "h": "hedge", "F": "fence"}
    for ty, row in enumerate(m):
        for tx, ch in enumerate(row):
            im.paste(to_image(tiles[ch2tile[ch]]), (tx * 16, ty * 16))
    items = []
    for k, x, y in world.OBJECTS:
        p = objs[k.upper()]
        items.append((y, x, y - len(p), p))
    rx, ry = world.ROUTE[0]
    items.append((ry * 16 + 16, rx * 16, ry * 16 + 16 - 21, tf[0]))
    for _, x, y, p in sorted(items, key=lambda t: t[0]):
        img = to_image(p)
        im.alpha_composite(img, (x, y))
    return im


if __name__ == "__main__":
    main()
