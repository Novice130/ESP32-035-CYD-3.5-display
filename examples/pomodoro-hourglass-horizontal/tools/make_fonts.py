#!/usr/bin/env python3
"""Generate include/hg_fonts.h: anti-aliased 8-bit fonts from Pillow's bundled Aileron (CC0)."""
import os
from PIL import Image, ImageDraw, ImageFont

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "include", "hg_fonts.h")

# name, pixel size, chars, tabular digits
FONTS = [
    ("FONT_BIG", 78, "0123456789:", True),
    ("FONT_BIG3", 60, "0123456789:", True),  # three-digit minutes (120:00)
    ("FONT_MED", 24, None, False),
    ("FONT_TXT", 18, None, False),
    ("FONT_SMALL", 14, None, False),
]
ASCII = "".join(chr(c) for c in range(32, 127))


def build(name, size, chars, tabular):
    font = ImageFont.load_default(size)
    chars = chars or ASCII
    ascent, descent = font.getmetrics()
    data = bytearray()
    entries = []
    zero = font.getlength("0")
    for ch in chars:
        adv = font.getlength(ch)
        l, t, r, b = font.getbbox(ch)
        w, h = max(0, r - l), max(0, b - t)
        off = len(data)
        if w and h:
            im = Image.new("L", (w, h), 0)
            ImageDraw.Draw(im).text((-l, -t), ch, font=font, fill=255)
            data += im.tobytes()
        if tabular and ch.isdigit():
            l += int((zero - adv) / 2)
            adv = zero
        entries.append((ord(ch), w, h, l, t, int(round(adv)), off))
    return name, ascent + descent, ascent, entries, data


with open(OUT, "w") as f:
    f.write("// Generated by tools/make_fonts.py (Aileron, CC0, via Pillow) - do not edit.\n#pragma once\n#include <stdint.h>\n\n")
    f.write("struct FontGlyph { uint8_t ch, w, h; int8_t xo; int8_t yo; uint8_t adv; uint16_t off; };\n")
    f.write("struct Font { const FontGlyph* glyphs; const uint8_t* data; uint8_t count, height, ascent; };\n\n")
    for spec in FONTS:
        name, height, ascent, entries, data = build(*spec)
        f.write(f"static const uint8_t {name}_DATA[{len(data)}] = {{\n")
        for i in range(0, len(data), 40):
            f.write(",".join(str(v) for v in data[i:i + 40]) + ",\n")
        f.write("};\n")
        f.write(f"static const FontGlyph {name}_G[{len(entries)}] = {{\n")
        for e in entries:
            f.write("{%d,%d,%d,%d,%d,%d,%d},\n" % e)
        f.write("};\n")
        f.write(f"static const Font {name} = {{ {name}_G, {name}_DATA, {len(entries)}, {height}, {ascent} }};\n\n")
print("wrote", os.path.relpath(OUT))
