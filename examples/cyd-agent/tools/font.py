def glyph_table():
    """returns list of (code, width, rows_as_ints)."""
    out = []
    for code in range(1, 128):
        ch = chr(code)
        if ch not in G:
            continue
        rows = G[ch]
        w = len(rows[0])
        assert all(len(r) == w for r in rows), ch
        assert len(rows) == 8, ch
        bits = []
        for r in rows:
            v = 0
            for i, c in enumerate(r):
                if c == "#":
                    v |= 1 << i
            bits.append(v)
        out.append((code, w, bits))
    return out
