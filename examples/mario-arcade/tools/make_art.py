#!/usr/bin/env python3
"""
make_art.py - generates ../include/art.h (sprites, themed tiles + scenery, font,
levels) from the Python art sources in this folder.

usage: python3 make_art.py [--preview DIR]
  --preview DIR   also write sprites.png, tiles.png and level_N.png overviews
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from PIL import Image  # noqa: E402
import sprites  # noqa: E402
import tiles  # noqa: E402
import levels  # noqa: E402
import font  # noqa: E402
from artlib import to_image  # noqa: E402

OUT = os.path.join(HERE, "..", "include", "art.h")


def rgb565(c):
    r, g, b = c
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)


class Emitter:
    def __init__(self):
        self.lines = []
        self.bytes = 0
        self.seen = {}

    def sprite(self, name, pix):
        h = len(pix)
        w = len(pix[0])
        pal = []
        idx = {}
        data = []
        for row in pix:
            for c in row:
                if c is None:
                    data.append(0)
                    continue
                k = rgb565(c)
                if k not in idx:
                    pal.append(k)
                    idx[k] = len(pal)
                data.append(idx[k])
        assert len(pal) < 256, name
        L = self.lines
        L.append("static const uint16_t PAL_%s[] = {0x0000,%s};" % (name, ",".join("0x%04X" % p for p in pal)))
        # identical pixel data (e.g. palette-swapped tiles) is stored once
        key = tuple(data)
        if key in self.seen:
            px = self.seen[key]
        else:
            px = "PX_" + name
            self.seen[key] = px
            L.append("static const uint8_t %s[] = {" % px)
            for i in range(0, len(data), 48):
                L.append("  " + ",".join(str(v) for v in data[i:i + 48]) + ",")
            L.append("};")
            self.bytes += len(data)
        L.append("static const Sprite SPR_%s = {%d, %d, %s, PAL_%s};" % (name, w, h, px, name))
        L.append("")
        self.bytes += 2 * len(pal)


SCENERY = ["HILL", "BUSH", "CLOUD", "CASTLE", "FLAG", "FLAGBALL"]


def main():
    preview = None
    if "--preview" in sys.argv:
        preview = sys.argv[sys.argv.index("--preview") + 1]

    e = Emitter()
    L = e.lines
    L += [
        "// =============================================================================",
        "//  art.h - GENERATED by tools/make_art.py - do not edit by hand.",
        "//  Hand-made fan-tribute pixel art (plumber, enemies, items, themed tiles),",
        "//  5x8 font and the level layouts (8 worlds x 4).",
        "// =============================================================================",
        "#pragma once",
        "#include <stdint.h>",
        "",
        "struct Sprite { uint16_t w, h; const uint8_t* px; const uint16_t* pal; };",
        "struct Glyph  { uint8_t w; uint8_t rows[8]; };",
        "struct LevelEnt { char kind; uint8_t col, row; };",
        "struct LevelDef { const char* name; uint8_t theme; uint16_t w, time, flag, castle;",
        "                  const char* const* rows; const LevelEnt* ents; uint8_t nents; };",
        "",
    ]

    # characters, enemies, items
    spr = sprites.build()
    for n, pix in spr.items():
        e.sprite(n, pix)
    poses = ["STAND", "WALK1", "WALK2", "WALK3", "JUMP"]
    for form, pre in (("SMALL", "MS"), ("BIG", "MB"), ("FIRE", "MF")):
        L.append("static const Sprite* const MARIO_%s[5] = {%s};" % (form, ",".join("&SPR_%s_%s" % (pre, p) for p in poses)))
    L.append("static const Sprite* const COIN_SPIN[4] = {&SPR_COIN0,&SPR_COIN1,&SPR_COIN2,&SPR_COIN1};")
    L.append("static const Sprite* const FIREBALL[4] = {&SPR_FIREBALL0,&SPR_FIREBALL1,&SPR_FIREBALL2,&SPR_FIREBALL3};")
    L.append("")

    # themed tiles + scenery
    sky = []
    for th in tiles.THEMES:
        t, s, rgb = tiles.build(th)
        sky.append(rgb565(rgb))
        for n in tiles.TILE_ORDER:
            e.sprite("T%s_%s" % (th, n), t[n])
        for n in SCENERY:
            e.sprite("S%s_%s" % (th, n), s[n])
    L.append("#define THEME_COUNT %d" % len(tiles.THEMES))
    for i, th in enumerate(tiles.THEMES):
        L.append("#define THEME_%s %d" % (th, i))
    for i, n in enumerate(tiles.TILE_ORDER):
        L.append("#define TS_%s %d" % (n, i))
    L.append("#define TILE_SPRITES %d" % len(tiles.TILE_ORDER))
    L.append("static const Sprite* const TILESPR[THEME_COUNT][TILE_SPRITES] = {")
    for th in tiles.THEMES:
        L.append("  {%s}," % ",".join("&SPR_T%s_%s" % (th, n) for n in tiles.TILE_ORDER))
    L.append("};")
    for n in SCENERY:
        L.append("static const Sprite* const SC_%s[THEME_COUNT] = {%s};" % (n, ",".join("&SPR_S%s_%s" % (th, n) for th in tiles.THEMES)))
    L.append("static const uint16_t SKY[THEME_COUNT] = {%s};" % ",".join("0x%04X" % c for c in sky))
    L.append("")

    # font
    glyphs = {code: (w, bits) for code, w, bits in font.glyph_table()}
    L.append("static const Glyph FONT[128] = {")
    for code in range(128):
        w, bits = glyphs.get(code, (0, [0] * 8))
        L.append("  {%d,{%s}}, // %r" % (w, ",".join(str(b) for b in bits), chr(code)))
    L.append("};")
    L.append("")

    # levels
    built = []
    for i, f in enumerate(levels.ALL):
        lv = f()
        rows, ents = lv.build()
        for w in lv.warnings():
            print("warning:", w)
        built.append((lv, rows))
        L.append("// %s (%s)" % (lv.name, lv.theme))
        L.append("static const char* const LV%d_ROWS[%d] = {" % (i, levels.ROWS))
        for r in rows:
            L.append('  "%s",' % r)
        L.append("};")
        L.append("static const LevelEnt LV%d_ENTS[] = {%s};" % (i, ",".join("{'%s',%d,%d}" % en for en in ents)))
        e.bytes += levels.ROWS * lv.w + 3 * len(ents)
    L.append("static const LevelDef LEVELS[] = {")
    for i, (lv, _) in enumerate(built):
        L.append('  {"%s", THEME_%s, %d, %d, %d, %d, LV%d_ROWS, LV%d_ENTS, sizeof(LV%d_ENTS) / sizeof(LevelEnt)},'
                 % (lv.name, lv.theme, lv.w, lv.time, lv.flag, lv.castle, i, i, i))
    L.append("};")
    L.append("#define LEVEL_COUNT %d" % len(built))
    L.append("#define LEVEL_ROWS %d" % levels.ROWS)
    L.append("")

    with open(OUT, "w") as f:
        f.write("\n".join(L) + "\n")
    print("wrote %s (%d KB of art data)" % (os.path.relpath(OUT), e.bytes // 1024))

    if preview:
        os.makedirs(preview, exist_ok=True)
        for i, (lv, rows) in enumerate(built):
            render_level(lv, rows).save(os.path.join(preview, "level_%d.png" % i))
        print("wrote level previews to", preview)


def render_level(lv, rows):
    t, s, sky = tiles.build(lv.theme)
    ch = {"#": "GROUND", "B": "BRICK", "b": "BRICK", "s": "BRICK", "u": "BRICK", "?": "Q0", "M": "Q0",
          "X": "HARD", "[": "PIPE_TL", "]": "PIPE_TR", "{": "PIPE_L", "}": "PIPE_R", "|": "TRUNK", "~": "LAVA0"}
    im = Image.new("RGBA", (lv.w * 16, levels.ROWS * 16), sky + (255,))
    for y, row in enumerate(rows):
        for x, c in enumerate(row):
            n = ch.get(c)
            if c == "T":
                left = x > 0 and row[x - 1] == "T"
                right = x + 1 < len(row) and row[x + 1] == "T"
                n = "TREE_M" if left and right else ("TREE_R" if left else "TREE_L")
            if n:
                im.alpha_composite(to_image(t[n]), (x * 16, y * 16))
            elif c == "o":
                im.alpha_composite(to_image(sprites.build()["COIN0"]), (x * 16 + 4, y * 16 + 1))
    im.alpha_composite(to_image(s["CASTLE"]), (lv.castle * 16, 128 - 80))
    spr = sprites.build()
    for k, x, y in lv.build()[1]:
        p = {"g": spr["GOOMBA"], "k": spr["KOOPA"], "p": spr["PIRANHA0"]}[k]
        img = to_image(p)
        im.alpha_composite(img, (x * 16, (y + 1) * 16 - img.height))
    return im.resize((im.width, im.height), Image.NEAREST)


if __name__ == "__main__":
    main()
